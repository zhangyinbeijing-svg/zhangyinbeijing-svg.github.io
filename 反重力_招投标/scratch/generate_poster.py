# Top Right Badges
def draw_pill(x, y, text, fill_color, text_color, font=font_badge, border=None):
    bbox = font.getbbox(text)
    tw = bbox[2] - bbox[0]
    th = bbox[3] - bbox[1]
    pw, ph = tw + 24, th + 14
    draw.rounded_rectangle([(x, y), (x + pw, y + ph)], radius=ph//2, fill=fill_color, outline=border, width=1)
    draw.text((x + 12, y + 5), text, fill=text_color, font=font)
    return x + pw

