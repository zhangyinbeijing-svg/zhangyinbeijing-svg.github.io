# Helper to draw a modern section card
def draw_section_box(x, y, w, h, title, category_name, cat_color, border_color):
    draw.rounded_rectangle([(x, y), (x + w, y + h)], radius=16, fill=(15, 23, 42), outline=border_color, width=2)
    # Header bar
    draw.rounded_rectangle([(x, y), (x + w, y + 60)], radius=16, fill=(23, 33, 58))
    draw.rectangle([(x, y + 40), (x + w, y + 60)], fill=(23, 33, 58)) # square bottom corners
    draw.line([(x, y + 60), (x + w, y + 60)], fill=border_color, width=1)
    
    # Title & Badge
    draw.text((x + 22, y + 14), title, fill=(255, 255, 255), font=font_sec_title)
    
    # Category badge on right
    bbox = font_card_tag.getbbox(category_name)
    tw = bbox[2] - bbox[0]
    draw.rounded_rectangle([(x + w - tw - 35, y + 16), (x + w - 18, y + 44)], radius=8, fill=cat_color[1], outline=cat_color[0], width=1)
    draw.text((x + w - tw - 27, y + 21), category_name, fill=cat_color[0], font=font_card_tag)

def draw_item_card(x, y, w, h, title, tag, lines, accent_color, fill_bg=(21, 32, 57)):
    draw.rounded_rectangle([(x, y), (x + w, y + h)], radius=10, fill=fill_bg, outline=(40, 56, 92), width=1)
    draw.rectangle([(x, y + 8), (x + 5, y + h - 8)], fill=accent_color) # left color stripe
    
    draw.text((x + 18, y + 10), title, fill=(255, 255, 255), font=font_card_title)
    if tag:
        bbox = font_card_tag.getbbox(tag)
        tw = bbox[2] - bbox[0]
        draw.rounded_rectangle([(x + w - tw - 26, y + 10), (x + w - 12, y + 32)], radius=5, fill=(30, 41, 69), outline=accent_color, width=1)
        draw.text((x + w - tw - 19, y + 13), tag, fill=accent_color, font=font_card_tag)
    
    curr_y = y + 42
    for line in lines:
        if line.startswith("•"):
            parts = line.split(":", 1)
            if len(parts) == 2:
                draw.text((x + 18, curr_y), parts[0] + ":", fill=(226, 232, 240), font=font_body_bold)
                fw = font_body_bold.getbbox(parts[0] + ":")[2] - font_body_bold.getbbox(parts[0] + ":")[0]
                draw.text((x + 22 + fw, curr_y), parts[1], fill=(148, 163, 184), font=font_body)
            else:
                draw.text((x + 18, curr_y), line, fill=(148, 163, 184), font=font_body)
        else:
            draw.text((x + 18, curr_y), line, fill=(148, 163, 184), font=font_body)
        curr_y += 24

